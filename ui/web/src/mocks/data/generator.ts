/**
 * Seeded, deterministic vendor feed: the same date always gives the same
 * items. Shaped like vendor-sim's feed (python/vendor-sim).
 */

export const MOCK_SEED = 42;
export const ITEMS_PER_DAY = 100;
export const DUPLICATES_PER_DAY = 9;
export const HEADLINE_PREFIX = '[SYNTHETIC] ';
export const FOOTER = 'Generated by premarket-ai vendor-sim. Not real news.';

const ORIGINALS_PER_DAY = ITEMS_PER_DAY - DUPLICATES_PER_DAY;
const DUPLICATES_OF_EACH_KIND = 3;
const SOURCE_NAME = 'Acme Market Wire';
// Item ids are <days since this date> * 1000 + <item number>, so an id
// alone says which day to generate.
const ID_EPOCH = '2020-01-01';
// Published between 16:00 ET the day before and 05:15 ET, as in vendor-sim.
const PUBLISH_WINDOW_MINUTES = 13 * 60 + 15;
const MONTH_NAME = new Intl.DateTimeFormat('en-US', {
  month: 'long',
  timeZone: 'UTC',
});

/** One trading date of the feed, in wire format. */
export interface GeneratedDay {
  date: string;
  run: IngestRunWire | null;
  /** Newest first, duplicates included. */
  items: NewsDetailWire[];
}

interface Story {
  headline: string;
  text: string;
  tickers: string[];
  domain: string;
  /** Defaults to an https URL on `domain`. */
  sourceUrl?: string;
}

/** Generates the feed of `date`. Weekends have no run and no items. */
export function generateDay(date: string, seed = MOCK_SEED): GeneratedDay {
  if (isWeekend(date)) {
    return {date, run: null, items: []};
  }
  const originals = generateOriginals(date, seed);
  const items = [...originals, ...generateDuplicates(date, seed, originals)];
  items.sort(newestFirst);
  return {date, run: doneRun(date), items};
}

/** The date and item number an id was built from, if it is one of ours. */
export function parseItemId(
  id: number,
): {date: string; number: number} | undefined {
  const number = id % 1000;
  if (!Number.isInteger(id) || id < 0 || number < 1 || number > ITEMS_PER_DAY) {
    return undefined;
  }
  return {date: addDays(ID_EPOCH, Math.floor(id / 1000)), number};
}

function itemId(date: string, number: number): number {
  return daysBetween(ID_EPOCH, date) * 1000 + number;
}

function vendorItemId(date: string, number: number): string {
  return `VND-${date.replaceAll('-', '')}-${String(number).padStart(3, '0')}`;
}

function doneRun(date: string): IngestRunWire {
  const started = addSeconds(newYorkTimeToUtc(date, 5, 30), 2);
  return {
    run_id: daysBetween(ID_EPOCH, date),
    status: 'DONE',
    started_at: started,
    finished_at: addSeconds(started, 3),
    rows_received: ITEMS_PER_DAY,
    dups: DUPLICATES_PER_DAY,
  };
}

function newestFirst(a: NewsDetailWire, b: NewsDetailWire): number {
  if (a.published_at !== b.published_at) {
    return a.published_at < b.published_at ? 1 : -1;
  }
  return b.id - a.id;
}

function generateOriginals(date: string, seed: number): NewsDetailWire[] {
  const random = createRandom(hashSeed(seed, date));
  const items: NewsDetailWire[] = [];
  for (let number = 1; number <= ORIGINALS_PER_DAY; number++) {
    const story =
      AWKWARD_STORIES.get(number) ??
      (random.next() < 0.85 ? realStory(random) : fakeStory(random));
    const minutes = random.int(0, PUBLISH_WINDOW_MINUTES);
    const publishedAt = newYorkTimeToUtc(addDays(date, -1), 16, minutes);
    items.push(makeItem(date, number, story, publishedAt));
  }
  return items;
}

/**
 * Three of each kind: exact copies, copies of the same URL with a reworded
 * headline, and stale copies of the previous trading date's items.
 */
function generateDuplicates(
  date: string,
  seed: number,
  originals: readonly NewsDetailWire[],
): NewsDetailWire[] {
  const random = createRandom(hashSeed(seed, date, 'duplicates'));
  const previousDay = generateOriginals(previousTradingDate(date), seed);
  const duplicates: NewsDetailWire[] = [];
  let number = ORIGINALS_PER_DAY + 1;
  for (let i = 0; i < DUPLICATES_OF_EACH_KIND; i++) {
    const source = random.pick(originals);
    duplicates.push(
      copyItem(date, number++, source, {
        published_at: addSeconds(source.published_at, random.int(1, 30) * 60),
      }),
    );
  }
  for (let i = 0; i < DUPLICATES_OF_EACH_KIND; i++) {
    const source = random.pick(originals);
    duplicates.push(
      copyItem(date, number++, source, {
        headline: `${source.headline} (update)`,
        published_at: addSeconds(source.published_at, random.int(31, 90) * 60),
      }),
    );
  }
  for (let i = 0; i < DUPLICATES_OF_EACH_KIND; i++) {
    duplicates.push(copyItem(date, number++, random.pick(previousDay), {}));
  }
  return duplicates;
}

function copyItem(
  date: string,
  number: number,
  source: NewsDetailWire,
  changes: Partial<NewsDetailWire>,
): NewsDetailWire {
  return {
    ...source,
    ...changes,
    id: itemId(date, number),
    vendor_item_id: vendorItemId(date, number),
    feed_date: date,
    is_dup: true,
    dup_of: source.vendor_item_id,
  };
}

function makeItem(
  date: string,
  number: number,
  story: Story,
  publishedAt: string,
): NewsDetailWire {
  const body = `${dateline(date)} ${story.text}\n\n${FOOTER}`;
  const path = `${date.replaceAll('-', '/')}/${slug(story.headline)}`;
  return {
    id: itemId(date, number),
    vendor_item_id: vendorItemId(date, number),
    feed_date: date,
    headline: HEADLINE_PREFIX + story.headline,
    excerpt: excerptOf(body),
    source_url:
      story.sourceUrl ??
      `https://${story.domain}/${path}-${String(number).padStart(3, '0')}`,
    source_domain: story.domain,
    published_at: publishedAt,
    tickers: story.tickers,
    synthetic: true,
    is_dup: false,
    dup_of: null,
    body,
  };
}

/** `NEW YORK, September 24 (Acme Market Wire) --` */
function dateline(date: string): string {
  const month = MONTH_NAME.format(new Date(`${date}T00:00:00Z`));
  return `NEW YORK, ${month} ${Number(date.slice(8))} (${SOURCE_NAME}) --`;
}

/** At most 280 characters of the body, on one line. */
function excerptOf(body: string): string {
  // Counted in characters (code points), like the backend.
  const chars = [...body.replace(/\s+/g, ' ').trim()];
  if (chars.length <= EXCERPT_MAX_CHARS) {
    return chars.join('');
  }
  return `${chars
    .slice(0, EXCERPT_MAX_CHARS - 3)
    .join('')
    .trimEnd()}...`;
}

function slug(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60);
}

function otherThan(random: Random, pool: readonly Company[], not: Company) {
  let other = random.pick(pool);
  while (other.ticker === not.ticker) {
    other = random.pick(pool);
  }
  return other;
}

const PEOPLE = ['Dana Whitfield', 'Marcus Oyelaran', 'Priya Natarajan'];
const AREAS = ['cloud infrastructure', 'payments', 'logistics', 'AI chips'];

function realStory(random: Random): Story {
  const company = random.pick(REAL_COMPANIES);
  const other = otherThan(random, REAL_COMPANIES, company);
  const who = `${company.name} (${company.ticker})`;
  const pct = random.int(2, 35);
  const revenue = random.int(5, 150);
  const quarter = random.int(1, 4);
  const amount = random.int(2, 40);
  const domain =
    random.next() < 0.8
      ? random.pick(TRUSTED_DOMAINS)
      : random.pick(LOW_QUALITY_DOMAINS);
  const stories: Array<Omit<Story, 'domain'>> = [
    {
      headline: `${company.short} reports Q${quarter} revenue of $${revenue}B, up ${pct}% from a year ago`,
      text: `${who} said revenue for its fiscal Q${quarter} reached $${revenue} billion, up ${pct}% from a year earlier. Management will discuss the results on its scheduled conference call.`,
      tickers: [company.ticker],
    },
    {
      headline: `${company.short} raises quarterly dividend to $${(amount / 10).toFixed(2)} per share`,
      text: `The board of ${who} approved a quarterly dividend of $${(amount / 10).toFixed(2)} per share, payable next month to shareholders of record.`,
      tickers: [company.ticker],
    },
    {
      headline: `${company.short} announces $${amount}B share repurchase program`,
      text: `${who} said its board authorized the repurchase of up to $${amount} billion of common stock, with no fixed end date.`,
      tickers: [company.ticker],
    },
    {
      headline: `${company.short} reaffirms full-year outlook of about ${pct}% revenue growth`,
      text: `${who} reaffirmed its full-year guidance and still expects revenue to grow about ${pct}% compared with last year.`,
      tickers: [company.ticker],
    },
    {
      headline: `${company.short} names ${random.pick(PEOPLE)} chief financial officer`,
      text: `${who} appointed a new chief financial officer, effective next month.\nThe outgoing CFO will stay on as an adviser during the transition.`,
      tickers: [company.ticker],
    },
    {
      headline: `${company.short} and ${other.short} announce multi-year partnership`,
      text: `${who} and ${other.name} (${other.ticker}) signed a multi-year partnership covering ${random.pick(AREAS)}. Financial terms were not disclosed.`,
      tickers: [company.ticker, other.ticker],
    },
  ];
  return {...random.pick(stories), domain};
}

function fakeStory(random: Random): Story {
  const company = random.pick(FAKE_COMPANIES);
  const other = otherThan(random, FAKE_COMPANIES, company);
  const who = `${company.name} (${company.ticker})`;
  const amount = random.int(2, 40);
  const domain =
    random.next() < 0.5
      ? random.pick(SPOOFED_DOMAINS)
      : random.pick(LOW_QUALITY_DOMAINS);
  const stories: Array<Omit<Story, 'domain'>> = [
    {
      headline: `${company.short} to be acquired by ${other.short} for $${amount}B in all-cash deal`,
      text: `${who} agreed to be acquired by ${other.name} (${other.ticker}) for $${amount} billion in cash, according to people familiar with the matter.`,
      tickers: [company.ticker, other.ticker],
    },
    {
      headline: `${company.short} wins regulatory approval for lead therapy`,
      text: `${who} said regulators approved its lead therapy after a fast-track review.`,
      tickers: [company.ticker],
    },
    {
      headline: `${company.short} signs $${amount}B supply contract with ${other.short}`,
      text: `${who} said it will supply ${other.name} (${other.ticker}) under a $${amount} billion multi-year contract starting next quarter.`,
      tickers: [company.ticker, other.ticker],
    },
  ];
  return {...random.pick(stories), domain};
}

